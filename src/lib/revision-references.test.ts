import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { receiveReference } from './reference-upload';
import { readImage } from './assets';
import { withPage } from './browser';
import { emptyWorkspace, workspaceSchema } from './schema';
import { decodeDeck, prepareGeneration } from './ai';
import { packWorkspace, unpackWorkspace } from './portable';
import { slideDocument } from './document';

describe('uploaded revision references', () => {
  let directory: string;
  beforeEach(async () => { directory = await mkdtemp(join(tmpdir(), 'cb-reference-')); vi.spyOn(process, 'cwd').mockReturnValue(directory); });
  afterEach(async () => { vi.restoreAllMocks(); await rm(directory, { recursive: true, force: true }); });
  const request = (bytes: Uint8Array, type = 'image/png', headers = {}) => new Request('http://localhost:3000/api/reference-images', { method: 'POST', headers: { 'Content-Type': type, 'X-File-Name': encodeURIComponent('Referência.png'), ...headers }, body: new Uint8Array(bytes) });
  it('validates real images, passes their pixels to revisions, and preserves originals in portable exports', async () => {
    const bytes = await withPage(async page => { await page.setViewport({ width: 2000, height: 1000 }); await page.setContent('<body style="margin:0;background:#f2591d"></body>'); return page.screenshot({ type: 'png' }); });
    const reference = await receiveReference(request(bytes));
    expect(reference).toMatchObject({ name: 'Referência.png', width: 2000, height: 1000 });
    expect(reference.original).toMatch(/\.png$/); expect(reference.preview).toMatch(/\.jpg$/);
    expect(await readImage(reference.original)).toEqual(Buffer.from(bytes));
    const preview = await readImage(reference.preview);
    const dimensions = await withPage(page => page.evaluate(async data => { const im = new Image(); im.src = data; await im.decode(); return [im.naturalWidth, im.naturalHeight]; }, `data:image/jpeg;base64,${preview.toString('base64')}`));
    expect(dimensions).toEqual([1568, 784]);
    const workspace = { ...emptyWorkspace, revisionReferences: [reference], revisionText: 'Use this photo', deck: { width: 300, height: 400, title: 'Test', slides: [{ html: '<p>Original</p>' }, { html: '<p>Keep me</p>' }] } };
    const operation = { signal: new AbortController().signal, progress: vi.fn(), usage: vi.fn() };
    const input = { ...workspace, instruction: workspace.revisionText, slideIndex: 0 };
    const message = await prepareGeneration(input, operation);
    expect(JSON.stringify(message)).toContain('UPLOADED REFERENCE 1 — Referência.png');
    expect(JSON.stringify(message)).toContain(preview.toString('base64'));
    const result = decodeDeck(JSON.stringify({ title: 'Test', slides: [{ html: `<img src="${reference.original}">` }] }), input);
    expect(result.assets?.[reference.original]).toBe(reference.original);
    expect(result.slides[1]).toEqual(workspace.deck.slides[1]);
    expect(result.width).toBe(300); expect(result.height).toBe(400);
    expect(slideDocument(result.slides[0].html, { [reference.original]: `data:image/png;base64,${Buffer.from(bytes).toString('base64')}` })).toContain('data:image/png;base64,');
    const generation = await prepareGeneration({ ...workspace, brief: 'Make a new slide' }, operation);
    expect(JSON.stringify(generation)).not.toContain(reference.original);
    expect(JSON.stringify(generation)).not.toContain(preview.toString('base64'));
    const newInput = { ...workspace, deck: null, brief: 'Create a new slide', generationTask: 'Use the attached reference with the exact title.', generationReferences: [reference] };
    const newMessage = await prepareGeneration(newInput, operation);
    expect(JSON.stringify(newMessage)).toContain(preview.toString('base64'));
    expect(JSON.stringify(newMessage)).toContain(newInput.generationTask);
    const created = decodeDeck(JSON.stringify({ title: 'New', slides: [{ html: `<img src="${reference.original}">` }] }), newInput);
    expect(created.originTask).toBe(newInput.generationTask);
    expect(created.assets?.[reference.original]).toBe(reference.original);
    const revised = decodeDeck(JSON.stringify({ title: 'New', slides: [{ html: 'Revised' }] }), { ...newInput, deck: created, instruction: 'Move the text' });
    expect(revised.originTask).toBe(newInput.generationTask);
    const conversationWorkspace = { ...workspace, revisionReferences: [], agent: { draft: 'Keep this draft', references: [], messages: [{ id: 'user', role: 'user' as const, text: 'Use the image', attachments: [reference] }] } };
    const restoredConversation = await unpackWorkspace(await packWorkspace(conversationWorkspace));
    expect(restoredConversation.agent).toEqual(conversationWorkspace.agent);
    const bundle = await packWorkspace(workspace);
    expect(Object.keys(bundle.assets)).toEqual(expect.arrayContaining([reference.original, reference.preview, reference.thumbnail]));
    expect((await unpackWorkspace(bundle)).revisionReferences).toEqual([reference]);
    const archived = { ...workspace, revisionReferences: [], recentRuns: [{ operation: 'revise' as const, outcome: 'success' as const, startedAt: 'now', durationMs: 100, instruction: 'Use this photo', inputs: { brief: '', directions: [], website: null, websiteNotes: '', images: [], width: 300, height: 400, target: 'Slide 1', revisionReferences: [reference] } }] };
    expect(Object.keys((await packWorkspace(archived)).assets)).toEqual(expect.arrayContaining([reference.original, reference.preview, reference.thumbnail]));
  }, 20_000);
  it('rejects unsupported, oversized, mislabeled and broken images without storing them', async () => {
    await expect(receiveReference(request(Buffer.from('<svg/>'), 'image/svg+xml'))).rejects.toThrow('PNG, JPEG or WebP');
    await expect(receiveReference(request(Buffer.from('fake'), 'image/png', { 'Content-Length': String(11 * 1024 * 1024) }))).rejects.toThrow('10 MB');
    await expect(receiveReference(request(new Uint8Array(10 * 1024 * 1024 + 1)))).rejects.toThrow('10 MB');
    await expect(receiveReference(request(Buffer.from('not png')))).rejects.toThrow('not a valid');
    await expect(receiveReference(request(Buffer.from([137,80,78,71,13,10,26,10])))).rejects.toThrow('could not be opened');
    await expect(receiveReference(request(Buffer.from('image'), 'image/png', { Origin: 'https://unrelated.example' }))).rejects.toThrow('must come from ContentBuilder');
  });
  it('loads older drafts with no attachments', () => {
    const { revisionReferences, ...old } = emptyWorkspace;
    expect(workspaceSchema.parse(old).revisionReferences).toEqual([]);
  });
});
